import { loadCards } from '../src/cards.js';
import { filterCards, createDeck, addCard, saveDeck, readDecks, exportJSON, importJSON, exportYDK, importYDK, totals } from '../src/core.js';
import assert from 'node:assert/strict';
const result = await loadCards();
assert.ok(result.cards.length > 10000, 'Expected the full archive, not a sample or single page');
const dragon = filterCards(result.cards, { query: 'Blue-Eyes White Dragon' }).find(c => c.name === 'Blue-Eyes White Dragon');
assert.ok(dragon?.desc && dragon.card_images[0]?.image_url);
const spells = filterCards(result.cards, { category: 'Spell' });
assert.ok(spells.length && spells.every(c => c.type === 'Spell Card'));
const links = filterCards(result.cards, { mechanic: 'Link' });
assert.ok(links.length && links.every(c => c.type.includes('Link')));
const xyz = filterCards(result.cards, { mechanic: 'Xyz' });
assert.ok(xyz.length && xyz.every(c => /xyz/i.test(c.type)));
const memory = new Map(), storage = { getItem: key => memory.get(key), setItem: (key, value) => memory.set(key, value) };
const deck = addCard(createDeck('Live API test'), dragon);
saveDeck(storage, [], deck);
assert.equal(readDecks(storage)[0].sections.main[0].card.name, dragon.name);
assert.deepEqual(totals(importJSON(exportJSON(deck))), totals(deck));
assert.deepEqual(totals(importYDK(exportYDK(deck), result.cards, 'YDK test')), totals(deck));
console.log(`Live API verified: ${result.cards.length} cards; search, mechanics, deck save/reopen, JSON, and YDK round trips passed.`);
